// ═══════════════════════════════════════════════════════════════════════════
// FILE: scripts/generate-tool-status-map.js
// Generates per-tool implementation/indexing status map from readiness report
// ═══════════════════════════════════════════════════════════════════════════

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const reportPath = path.join(ROOT, 'docs', 'reports', 'tool-readiness-report.json');
const registryPath = path.join(ROOT, 'src', 'lib', 'tools-registry.ts');
const outPath = path.join(ROOT, 'src', 'lib', 'tool-status-map.ts');

function parseRegistrySlugs(source) {
  const regex = /slug:\s*'([^']+)'/g;
  const slugs = [];
  let match;

  while ((match = regex.exec(source)) !== null) {
    slugs.push(match[1]);
  }

  return Array.from(new Set(slugs));
}

function generateFileContent(statusMap) {
  const lines = Object.entries(statusMap)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slug, status]) => `  '${slug}': { implementationStatus: '${status.implementationStatus}', indexingStatus: '${status.indexingStatus}' },`)
    .join('\n');

  return `// ═══════════════════════════════════════════════════════════════════════════
// FILE: src/lib/tool-status-map.ts
// AUTO-GENERATED by scripts/generate-tool-status-map.js
// Do not edit manually. Re-generate with: npm run tools:status
// ═══════════════════════════════════════════════════════════════════════════

export type ToolRolloutStatus = {
  implementationStatus: 'planned' | 'in-progress' | 'ready';
  indexingStatus: 'index' | 'noindex';
};

export const TOOL_STATUS_MAP: Record<string, ToolRolloutStatus> = {
${lines}
};
`;
}

function main() {
  if (!fs.existsSync(reportPath)) {
    throw new Error(`Readiness report not found: ${reportPath}. Run npm run tools:audit first.`);
  }

  const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
  const registrySource = fs.readFileSync(registryPath, 'utf8');
  const registrySlugs = parseRegistrySlugs(registrySource);

  const readySet = new Set(report.recommendations?.readyIndexCandidates || []);
  const noindexSet = new Set(report.recommendations?.keepNoindexUntilReady || []);
  const contentOnlySet = new Set(report.details?.contentOnly || []);

  const statusMap = {};

  for (const slug of registrySlugs) {
    if (readySet.has(slug)) {
      statusMap[slug] = {
        implementationStatus: 'ready',
        indexingStatus: 'index',
      };
      continue;
    }

    if (contentOnlySet.has(slug)) {
      statusMap[slug] = {
        implementationStatus: 'in-progress',
        indexingStatus: 'noindex',
      };
      continue;
    }

    if (noindexSet.has(slug)) {
      statusMap[slug] = {
        implementationStatus: 'planned',
        indexingStatus: 'noindex',
      };
      continue;
    }

    statusMap[slug] = {
      implementationStatus: 'ready',
      indexingStatus: 'index',
    };
  }

  fs.writeFileSync(outPath, generateFileContent(statusMap), 'utf8');

  const totals = Object.values(statusMap).reduce(
    (acc, s) => {
      acc[`${s.implementationStatus}:${s.indexingStatus}`] =
        (acc[`${s.implementationStatus}:${s.indexingStatus}`] || 0) + 1;
      return acc;
    },
    {},
  );

  console.log('🧭 Tool status map generated');
  console.log(`   Output: ${path.relative(ROOT, outPath)}`);
  console.log(`   Tools:  ${registrySlugs.length}`);
  Object.entries(totals)
    .sort(([a], [b]) => a.localeCompare(b))
    .forEach(([key, count]) => {
      console.log(`   ${key.padEnd(22)} ${count}`);
    });
}

if (require.main === module) {
  main();
}

module.exports = { main };
